class ConcreteResult {
  final double volume;
  final double cementKg;
  final double cementBags;
  final double sandM3;
  final double sandBrass;
  final double aggregateM3;
  final double aggregateBrass;
  final double waterLitres;

  const ConcreteResult({
    required this.volume,
    required this.cementKg,
    required this.cementBags,
    required this.sandM3,
    required this.sandBrass,
    required this.aggregateM3,
    required this.aggregateBrass,
    required this.waterLitres,
  });
}
